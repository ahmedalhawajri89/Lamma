    /**
     * ينسخ أغلفة المقالات إلى `storage/app/public/posts`.
     *
     * الصور مُتتبَّعة في `public/assets/img` لأنها جزء من تصميم الموقع، أما
     * `storage/app/public` فمتجاهَل في git كما ينبغي — فيه ما يرفعه المستخدمون.
     * ولولا هذا النسخ لكانت كل بطاقة مقال على نسخةٍ جديدة تطلب صورةً غير
     * موجودة وتردّ ‏403 صامتة: البذرة تكتب المسار، ولا أحد يضع الملف.
     */
    private function publishCovers(): void
    {
        $target = storage_path('app/public/posts');

        if (! is_dir($target)) {
            mkdir($target, 0755, true);
        }

        foreach (glob(public_path('assets/img/post-*.webp')) ?: [] as $source) {
            $destination = $target.DIRECTORY_SEPARATOR.basename($source);

            // لا نكتب فوق ملف موجود: قد يكون المحرّر استبدل الغلاف من اللوحة
            if (! is_file($destination)) {
                copy($source, $destination);
            }
        }
    }

