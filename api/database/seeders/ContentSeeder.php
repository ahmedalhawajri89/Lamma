            ],
        ];

        foreach ($rows as $row) {
            Post::updateOrCreate(['slug' => $row['slug']], [
                'title' => $row['title'],
                'excerpt' => $row['excerpt'],
                'body' => $row['body'],
                'category_id' => $categoryIds[$row['category']],
                'cover_path' => "posts/{$row['image']}",
                // زمن القراءة يُحسب من النصّ لا يُكتب باليد: رقم مكتوب يكذب
                // بصمت أول مرة يُحرَّر فيها المقال. ‏٢٠٠ كلمة في الدقيقة.
                'read_minutes' => max(1, (int) ceil(count(preg_split('/\s+/u', trim($row['body']), -1, PREG_SPLIT_NO_EMPTY)) / 200)),
                'status' => PostStatus::Published,
